"""Writes numbers/numbers.json and numbers/provenance.md.

numbers.json keeps only the tags that paper/ml4h_final.tex.in uses. Its source
is numbers/numbers_all.json when present (written by analysis/coletar_numeros.py
from outputs/), otherwise numbers.json itself. provenance.md is one Markdown
table, Tag | Value | Script | Output file | Cell, in order of first appearance
in the paper.

    python numbers/make_provenance.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[1]
NUM = RAIZ / "numbers"
TAG = re.compile(r"\{\{([A-Za-z0-9\-]+)\}\}")


def celula_md(v: object) -> str:
    return str(v).replace("|", r"\|").replace("\n", " ")


def main() -> int:
    tex = (RAIZ / "paper" / "ml4h_final.tex.in").read_text()
    ordem = list(dict.fromkeys(TAG.findall(tex)))
    fonte = NUM / "numbers_all.json"
    if not fonte.exists():
        fonte = NUM / "numbers.json"
    todos = json.loads(fonte.read_text())
    faltam = [t for t in ordem if t not in todos]
    if faltam:
        print("missing tags:", ", ".join(faltam))
        return 1
    usados = set(ordem)
    num = {k: v for k, v in todos.items() if k in usados}
    (NUM / "numbers.json").write_text(json.dumps(num, indent=1, ensure_ascii=False))

    linhas = [
        "# Provenance of every number in the paper",
        "",
        "Generated by `numbers/make_provenance.py` from `numbers/numbers.json`; do not edit by hand.",
        "",
        f"The paper uses {len(ordem)} tags (`{{{{TAG}}}}` in `paper/ml4h_final.tex.in`), listed in order of first",
        "appearance. *Script* is the analysis script that computed the aggregate (all are in `analysis/`; in",
        "`numbers.json` the `script` field keeps the script's path inside the authors' pipeline). *Output file*",
        "is the aggregate table in `outputs/` that holds the value, and *Cell* says which row/column of that table",
        "`analysis/coletar_numeros.py` reads (descriptions are in Portuguese, as in the code).",
        "",
        "| Tag | Value | Script | Output file | Cell |",
        "|---|---|---|---|---|",
    ]
    for t in ordem:
        v = num[t]
        script = "analysis/" + Path(v["script"]).name
        linhas.append(f"| `{t}` | {celula_md(v['valor'])} | `{script}` | `{v['arquivo']}` | {celula_md(v['celula'])} |")
    (NUM / "provenance.md").write_text("\n".join(linhas) + "\n")
    print(f"numbers.json: {len(num)} tags (from {fonte.name}); provenance.md written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
